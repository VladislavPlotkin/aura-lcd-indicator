// CharToLCDIndex converts a Unicode rune to its sequential LCD index.
// Returns 0 (space) for unknown characters.
// ASCII 0x20-0x7F: maps through cgromToIndexMap.
// Cyrillic: maps through cyrillicMap → CGROM code → cgromToIndexMap.
func CharToLCDIndex(char rune) byte {
	// ASCII passthrough
	if char >= 0x20 && char <= 0x7F {
		if idx, ok := cgromToIndexMap[byte(char)]; ok {
			return idx
		}
	}

	// Cyrillic
	if cgrom, ok := cyrillicMap[char]; ok {
		if idx, ok := cgromToIndexMap[cgrom]; ok {
			return idx
		}
	}

	// Unknown → space (index 0)
	return 0
}

// CGROMToIndex converts a raw CGROM code to its sequential index.
// Returns LCD_CGromSize (out of range) for unknown codes.
func CGROMToIndex(code byte) byte {
	if idx, ok := cgromToIndexMap[code]; ok {
		return idx
	}
	return byte(LCD_CGromSize) // out of range marker
}

// SplitToDisplay prepares a string for LCD: truncates to rows*cols,
// pads with spaces on the right.
func SplitToDisplay(text string, rows, cols int) string {
	total := rows * cols
	runes := []rune(text)
	if len(runes) > total {
		runes = runes[:total]
	}
	if len(runes) < total {
		padded := make([]rune, total)
		copy(padded, runes)
		for i := len(runes); i < total; i++ {
			padded[i] = ' '
		}
		runes = padded
	}
	return string(runes)
}
